// compiles contracts/*.sol with solc-js into contracts/out/*.json (abi + bytecode).
// evm version "paris" keeps the bytecode runnable on the local test chain as well as base sepolia.
import solc from "solc";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

const files = { "BeefEscrow.sol": "contracts/BeefEscrow.sol", "MockUSDC.sol": "contracts/test/MockUSDC.sol" };
const input = {
  language: "Solidity",
  sources: Object.fromEntries(Object.entries(files).map(([k, p]) => [k, { content: readFileSync(p, "utf8") }])),
  settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: "paris", outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } } },
};
const findImports = (p) => {
  try { return { contents: readFileSync(path.join("node_modules", p), "utf8") }; } catch { return { error: `not found: ${p}` }; }
};
const out = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
const errors = (out.errors ?? []).filter((e) => e.severity === "error");
for (const e of out.errors ?? []) console.error(e.formattedMessage);
if (errors.length) process.exit(1);
mkdirSync("contracts/out", { recursive: true });
for (const [file, contracts] of Object.entries(out.contracts)) {
  for (const [name, c] of Object.entries(contracts)) {
    if (!Object.keys(files).includes(file)) continue;
    writeFileSync(`contracts/out/${name}.json`, JSON.stringify({ contractName: name, compiler: `solc ${solc.version()}`, abi: c.abi, bytecode: "0x" + c.evm.bytecode.object }, null, 2));
    console.log(`compiled ${name} (${c.evm.bytecode.object.length / 2} bytes)`);
    if (name === "BeefEscrow") {
      writeFileSync("src/lib/wallet/escrow-abi.ts", `// generated by scripts/compile-contracts.mjs from contracts/BeefEscrow.sol. do not edit.\nexport const BEEF_ESCROW_ABI = ${JSON.stringify(c.abi, null, 2)} as const;\n`);
    }
  }
}
