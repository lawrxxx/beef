// generates supabase/seed.sql from src/data/seed.ts so the database demo matches
// the local demo exactly. run: npm run db:seed-sql
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { ASSETS } from "../src/lib/market/assets";
import { ACHIEVEMENTS } from "../src/lib/score";
import {
  seedComments, seedCommunities, seedDaily, seedDuels, seedFollows, seedMemberships, seedNotifications,
  seedPosts, seedReactions, seedUsers,
} from "../src/data/seed";

const uuid = (key: string) => {
  const h = createHash("sha1").update("beef:" + key).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return `array[${v.map(q).join(",")}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const uq = (id: string | undefined | null) => (id ? `'${uuid(id)}'` : "null");
const out: string[] = ["-- generated by scripts/generate-seed-sql.ts. do not edit by hand.", "begin;", ""];

out.push("insert into stock_assets (ticker, name, sector, tokenized) values");
out.push(ASSETS.map((a) => `  (${q(a.ticker)}, ${q(a.name)}, ${q(a.sector)}, ${q(!!a.tokenized)})`).join(",\n") + ";\n");

out.push("insert into achievements (id, name, description, emoji) values");
out.push(ACHIEVEMENTS.map((a) => `  (${q(a.id)}, ${q(a.name)}, ${q(a.description)}, ${q(a.emoji)})`).join(",\n") + ";\n");

out.push("-- demo profiles (no auth.users rows: they can't sign in)");
out.push("insert into profiles (id, username, display_name, bio, avatar_emoji, avatar_color, favorite_stocks, is_adult, onboarded, created_at) values");
out.push(seedUsers.map((u) => `  (${uq(u.id)}, ${q(u.username)}, ${q(u.displayName)}, ${q(u.bio)}, ${q(u.avatar)}, ${q(u.avatarColor)}, ${q(u.favoriteStocks)}, true, true, ${q(u.joinedAt)})`).join(",\n") + ";\n");

out.push("insert into communities (id, slug, name, description, emoji, tickers, created_by, created_at) values");
out.push(seedCommunities.map((c) => `  (${uq(c.id)}, ${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${q(c.emoji)}, ${q(c.tickers)}, ${uq(c.createdBy)}, ${q(c.createdAt)})`).join(",\n") + ";\n");
out.push("insert into community_members (community_id, user_id) values");
out.push(seedMemberships.map((m) => `  (${uq(m.communityId)}, ${uq(m.userId)})`).join(",\n") + ";\n");

out.push("-- duels are inserted before snapshots/settlements; triggers allow this because status is set on insert");
for (const d of seedDuels) {
  const t = d.terms;
  out.push(`insert into duels (id, created_by, title, stake, visibility, is_open, status, deadline, deadline_label, invite_expires_at, lock_at, activated_at, community_id, featured, methodology, provider, market_timezone, price_rule, settlement_rule, calculation_version, simulated_funds, created_at) values (${uq(d.id)}, ${uq(d.createdBy)}, ${q(d.title ?? null)}, ${d.stake}, ${q(d.visibility)}, ${q(d.open)}, ${q(d.status)}, ${q(d.deadline)}, ${q(d.deadlineLabel)}, ${q(d.inviteExpiresAt)}, ${q(d.lockAt ?? null)}, ${q(d.activatedAt ?? null)}, ${uq(d.communityId)}, ${q(!!d.featured)}, ${q(t.methodology)}, ${q(t.provider)}, ${q(t.marketTimezone)}, ${q(t.priceRule)}, ${q(t.settlementRule)}, ${q(t.calculationVersion)}, true, ${q(d.createdAt)});`);
  out.push(`insert into duel_participants (duel_id, user_id, ticker, accepted, accepted_at) values ${d.participants.map((p) => `(${uq(d.id)}, ${p.userId ? uq(p.userId) : "null"}, ${q(p.ticker)}, ${q(p.accepted)}, ${q(p.acceptedAt ?? null)})`).join(", ")};`);
  for (const sn of [...d.startSnapshots, ...d.endSnapshots]) {
    out.push(`insert into duel_price_snapshots (duel_id, ticker, kind, price, adjusted_price, session, price_timestamp, source, simulated) values (${uq(d.id)}, ${q(sn.ticker)}, ${q(sn.kind)}, ${sn.price}, ${q(sn.adjustedPrice ?? null)}, ${q(sn.session)}, ${q(sn.timestamp)}, ${q(sn.source)}, ${q(sn.simulated)});`);
  }
  const st = d.settlement;
  if (st && st.status !== "needs_verification") {
    const payload = { ...st, duelId: uuid(d.id), winners: st.winners.map(uuid), entries: st.entries.map((e) => ({ ...e, userId: uuid(e.userId) })) };
    out.push(`insert into duel_settlements (duel_id, status, winner_ids, winning_ticker, margin_pct, calculation_version, methodology, source, simulated, start_session, end_session, explanation, payload, settled_at) values (${uq(d.id)}, ${q(st.status)}, array[${st.winners.map((w) => uq(w)).join(",")}]::uuid[], ${q(st.winningTicker ?? null)}, ${st.marginPct}, ${q(st.calculationVersion)}, ${q(st.methodology)}, ${q(st.source)}, ${q(st.simulated)}, ${q(st.startSession)}, ${q(st.endSession)}, ${q(st.explanation)}, ${q(JSON.stringify(payload))}::jsonb, ${q(st.settledAt)});`);
    out.push(`insert into settlement_audit_logs (duel_id, at, action, detail) values (${uq(d.id)}, ${q(st.settledAt)}, 'settle.recorded', ${q(`${st.status}: ${st.explanation}`)});`);
  }
  if (st?.status === "needs_verification") {
    out.push(`insert into settlement_audit_logs (duel_id, at, action, detail) values (${uq(d.id)}, ${q(st.settledAt)}, 'settle.paused', ${q(st.issues.join("; "))});`);
  }
}
out.push("");

out.push("insert into posts (id, author_id, kind, body, duel_id, community_id, tickers, created_at) values");
out.push(seedPosts.map((p) => `  (${uq(p.id)}, ${uq(p.authorId)}, ${q(p.kind)}, ${q(p.body)}, ${uq(p.duelId)}, ${uq(p.communityId)}, ${q(p.tickers)}, ${q(p.createdAt)})`).join(",\n") + ";\n");
const preds = seedPosts.filter((p) => p.prediction);
out.push("insert into predictions (post_id, user_id, pick, versus, horizon) values");
out.push(preds.map((p) => `  (${uq(p.id)}, ${uq(p.authorId)}, ${q(p.prediction!.pick)}, ${q(p.prediction!.versus)}, ${q(p.prediction!.horizon)})`).join(",\n") + "\n  on conflict do nothing;\n");

const pc = seedComments.filter((c) => c.targetType === "post"), dc = seedComments.filter((c) => c.targetType === "duel");
out.push("insert into post_comments (id, post_id, author_id, body, created_at) values");
out.push(pc.map((c) => `  (${uq(c.id)}, ${uq(c.targetId)}, ${uq(c.authorId)}, ${q(c.body)}, ${q(c.createdAt)})`).join(",\n") + ";\n");
out.push("insert into duel_comments (id, duel_id, author_id, body, created_at) values");
out.push(dc.map((c) => `  (${uq(c.id)}, ${uq(c.targetId)}, ${uq(c.authorId)}, ${q(c.body)}, ${q(c.createdAt)})`).join(",\n") + ";\n");

const pr = seedReactions.filter((r) => r.targetType === "post"), dr = seedReactions.filter((r) => r.targetType === "duel");
out.push("insert into post_reactions (post_id, user_id, kind) values");
out.push(pr.map((r) => `  (${uq(r.targetId)}, ${uq(r.userId)}, ${q(r.kind)})`).join(",\n") + ";\n");
out.push("insert into duel_reactions (duel_id, user_id, kind) values");
out.push(dr.map((r) => `  (${uq(r.targetId)}, ${uq(r.userId)}, ${q(r.kind)})`).join(",\n") + ";\n");

out.push("insert into follows (follower_id, followee_id) values");
out.push(seedFollows.map((f) => `  (${uq(f.followerId)}, ${uq(f.followeeId)})`).join(",\n") + ";\n");

out.push("insert into notifications (user_id, actor_id, kind, text, href, read, created_at) values");
out.push(seedNotifications.map((n) => `  (${uq(n.userId)}, ${uq(n.actorId)}, ${q(n.kind)}, ${q(n.text)}, ${q(n.href)}, ${q(n.read)}, ${q(n.createdAt)})`).join(",\n") + ";\n");

out.push("insert into daily_beefs (session, ticker_a, ticker_b) values");
out.push(seedDaily.map((d) => `  (${q(d.session)}, ${q(d.a)}, ${q(d.b)})`).join(",\n") + ";\n");
const picks = seedDaily.flatMap((d) => Object.entries(d.picks).map(([u, t]) => `  (${q(d.session)}, ${uq(u)}, ${q(t)})`));
out.push("-- historical picks bypass the 'before open' policy because seed runs as the service role");
out.push("insert into daily_picks (session, user_id, ticker) values");
out.push(picks.join(",\n") + ";\n");

// rivalries for completed 1v1 duels
const riv = new Map<string, { a: string; b: string; wa: number; wb: number; dr: number; total: number; last: string }>();
for (const d of seedDuels.filter((x) => x.participants.length === 2 && x.status === "completed" && x.settlement)) {
  const [x, y] = d.participants.map((p) => uuid(p.userId)).sort();
  const key = `${x}:${y}`;
  const r = riv.get(key) ?? { a: x, b: y, wa: 0, wb: 0, dr: 0, total: 0, last: uuid(d.id) };
  r.total++;
  r.last = uuid(d.id);
  if (d.settlement!.status === "draw") r.dr++;
  else if (uuid(d.settlement!.winners[0]) === x) r.wa++;
  else r.wb++;
  riv.set(key, r);
}
out.push("insert into rivalries (user_a, user_b, wins_a, wins_b, draws, total, last_duel_id) values");
out.push(Array.from(riv.values()).map((r) => `  ('${r.a}', '${r.b}', ${r.wa}, ${r.wb}, ${r.dr}, ${r.total}, '${r.last}')`).join(",\n") + ";\n");

out.push("commit;");
writeFileSync("supabase/seed.sql", out.join("\n") + "\n");
console.log(`wrote supabase/seed.sql (${out.length} statements/blocks)`);
